-- Run this once in the Supabase SQL editor if the loans table does not exist.
-- The API model alone does not migrate an existing production database.
create table if not exists public.loans (
    id bigint generated by default as identity primary key,
    group_id bigint not null references public.groups(id) on delete cascade,
    from_user uuid not null references public.users(id),
    to_user uuid not null references public.users(id),
    amount numeric(10,2) not null check (amount > 0),
    note text,
    created_at timestamptz not null default now(),
    constraint loans_distinct_users check (from_user <> to_user)
);

create index if not exists loans_group_id_idx on public.loans(group_id);
create index if not exists loans_from_user_idx on public.loans(from_user);
create index if not exists loans_to_user_idx on public.loans(to_user);
